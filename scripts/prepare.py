"""Export the map's fixed geometry to web/geo.js for the live editor (web/index.html)."""
import json
import shapefile
from shapely.geometry import shape, Polygon, LineString
from build import xy, land_union, CAPITALS, X0, Y0, X1, Y1

NAMES = {  # editor labels
    "Constantinople": "君士坦丁堡（拜占庭）",
    "Chang'an": "長安（唐）",
    "Asuka": "飛鳥（日本）",
    "Geumseong": "金城（新羅）",
    "Rasa": "邏些（吐蕃）",
    "Medina": "麥地那（阿拉伯）",
}
TAIWAN_BOX = (119.9, 21.8, 122.2, 25.4)

def ring(coords):
    return [[round(x, 3), round(y, 3)] for x, y in coords]

def in_box_xy(p, box):
    x0, y0 = xy(box[0], box[3])
    x1, y1 = xy(box[2], box[1])
    c = p.centroid
    return x0 < c.x < x1 and y0 < c.y < y1

def taiwan():
    """The base map draws Taiwan with a few vertices; Natural Earth 10m land has the real outline."""
    lon0, lat0, lon1, lat1 = TAIWAN_BOX
    box = Polygon([(lon0, lat0), (lon1, lat0), (lon1, lat1), (lon0, lat1)])
    parts = []
    for s in shapefile.Reader("data/land/ne_10m_land").shapes():
        if s.bbox[0] > lon1 or s.bbox[2] < lon0 or s.bbox[1] > lat1 or s.bbox[3] < lat0:
            continue
        g = shape(s.__geo_interface__)
        parts += [p for p in getattr(g, "geoms", [g]) if p.intersects(box)]
    island = max(parts, key=lambda p: p.area)
    return ring(LineString([xy(lon, lat) for lon, lat in island.exterior.coords]).simplify(0.03).coords)

def himalaya_spine(n=60):
    """Midline of the Natural Earth Himalayas polygon, west to east."""
    r = shapefile.Reader("data/regions/ne_50m_geography_regions_polys")
    poly = next(shape(s.__geo_interface__) for s, rec in zip(r.shapes(), r.records()) if rec["NAME"] == "HIMALAYAS")
    lon0, _, lon1, _ = poly.bounds
    pts = []
    for i in range(n):
        lon = lon0 + (lon1 - lon0) * (i + 0.5) / n
        seg = poly.intersection(LineString([(lon, -90), (lon, 90)]))
        if not seg.is_empty:
            _, la, _, lb = seg.bounds
            pts.append(xy(lon, (la + lb) / 2))
    return ring(pts)

def main():
    crop = Polygon([(X0, Y0), (X1, Y0), (X1, Y1), (X0, Y1)])
    land = land_union().intersection(crop.buffer(3))
    polys = []
    for p in getattr(land, "geoms", [land]):
        # Islets under 0.15 (only Bornholm here) are specks at this scale; Taiwan is replaced below
        if p.area < 0.15 or in_box_xy(p, TAIWAN_BOX):
            continue
        polys.append({"rings": [ring(p.exterior.coords)] + [ring(i.coords) for i in p.interiors]})
    polys.append({"rings": [taiwan()], "detailed": True})
    geo = {
        "view": [round(v, 3) for v in (X0, Y0, X1 - X0, Y1 - Y0)],
        "land": polys,
        "spine": himalaya_spine(),
        "capitals": [{"id": k, "name": NAMES[k], "xy": [round(c, 3) for c in xy(lon, lat)]} for k, (lat, lon) in CAPITALS.items()],
    }
    with open("web/geo.js", "w") as f:
        f.write("// Generated by scripts/prepare.py — do not edit.\nwindow.GEO = ")
        json.dump(geo, f, separators=(",", ":"), ensure_ascii=False)
        f.write(";\n")

if __name__ == "__main__":
    main()
